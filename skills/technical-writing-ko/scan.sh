#!/usr/bin/env bash
[ -n "$1" ] || { echo "사용법: bash scan.sh <파일>" >&2; exit 2; }
[ -f "$1" ] || { echo "파일이 없습니다: $1" >&2; exit 2; }
[ -r "$1" ] || { echo "파일을 읽을 수 없습니다: $1" >&2; exit 2; }
F="$1"
body() { awk '/^[[:space:]]*```/{c=!c; next} !c {gsub(/`[^`]*`/, "``"); print NR "\t" $0}' "$1"; }
hit() { echo "--- $1 ---"; body "$F" | grep -E "$2"; }
removal() {
hit '줄표'           '—|―|(^|[^0-9])–|–([^0-9]|$)|[^[:space:]|>] --? [^[:space:]|]'
hit '꺽쇠'           '「|」|『|』|｢|｣'
hit '중간점'         '·|‧|・|･'
hit '이중피동'       '되어[지진질졌짐집]|보여[지진질졌짐집]|불려[지진질졌짐집]|쓰여[지진질졌짐집]|잊혀[지진질졌짐집]|나뉘어[지진질졌짐집]|여겨[지진질졌짐집]'
hit '곡선따옴표'     '“|”|‘|’'
hit '메타 담화'      '결론적으로|결론부터 (말|말씀)|요약하면|앞서 (설명|말씀)|아시다시피|본질적으로|시사하는 바|(살펴|알아)보겠습니다|(정직|솔직)하게 말하(면|자면)|솔직히 말하(면|자면)'
hit '번역투 조사'    '에 대[해한]|[을를] 통[해한]|에 의(해|한)|에서의|으로의|에의'
hit '접속어 뒤 쉼표' '(^|[[:space:]])(그리고|그러나|그런데|그러므로|하지만|따라서|또한|그래서|즉|특히|다만|게다가|한편),'
hit '굳은 오타'      '됬|되요|할께|몇일|웬지|왠만|어떻해'
}
candidates() {
hit '과장어'         '강력한|강력하게|원활한|원활하게|획기적|혁신적|손쉽게|간편하게|매끄럽게|완벽하게|극대화|핵심적인|필수적인|놀라운'
hit '강조 부사'      '매우|정말|굉장히|상당히|사실상|실제로|확실히'
hit '막연한 출처'    '연구에 따르면|업계에서는|전문가들은|일반적으로 알려|흔히 말하|많은 사람들이'
hit '대조와 의문'    '(이|가) 아니라|뿐만 아니라|단순(한|히) .{0,15}아니|까요?\?'
hit '형식 틀'        '중요한 (것|점)은|라는 점에서|측면에서|것이다|것입니다|첫째|둘째|셋째|오늘날|바야흐로|결국,|종합하면|정리하자면'
hit '번역투 후보'    '가지고 있|갖고 있|(으로|로) 인(해|하여|한)|위해(서| |,|$)|에 있어|의 경우|로부터|하나의|중 하나|에 위치|에도 불구하고|필요로 하|의거|[을를] 요하|금번|상기|익일|되어 있|돼 있|시켰|시킨다|시키는'
hit '직역 어휘'      '[0-9]+시판|(새|옛|이전|최신) 판|(^|[^헷])갈(린다|립니다)|가른다|가릅니다|(한|두|세) 축|축으로|같은 결|결이 (다르|같)|닫힌다|닫힙니다|조용히|떠받치|하중 지지|걷어|실측|흐려지|흔들리|해자|기둥|층위|한 겹|박아|박는|박힌|박혀|들고 있|쏜다|쏩니다|미러링|기회의 창|건네|에 가깝|핵심은|단추|이름표|꼬리표|고르개|뒤판|본보기|흉내 서버|정본|관문|갈래|거르기|거르고|원천|입구|(문장|항목) [0-9]+줄|(제목|버튼|머리|탭|필터|칩) 줄|스스로|값이 어긋|묶어 (보내|보낸|보냅)|준비해 (두|놓)'
hit '순우리말 직역체' '시험|기계 (스캔|검사)|(열린|해당|끝난|확인된|단) 건|알림 글|붙(는다|습니다|은 |인다|입니다)|에 더(한다|합니다|해 |했)|읽어 ?내|[을를] 읽(는다|습니다)|신호|물음|답을 고르|(설정|입력|검색|메모|이름) 칸|(AI|API|함수|스킬|도구)[을를] 부르|부르지 않|부를 때|꾸미는|꾸민다|꾸며|수식하는 절|[이가] (둘|셋|넷)([ .,]|$)|할 사람|(파일|이미지|사진)[을를]? 올(린|립|려)|내려받|(^|[[:space:](])(한|두|세|네|몇|여러|[0-9]+) ?(벌|켤레|그루)([[:space:].,)!?]|만|씩|로|을|이|과|의|도|은|째|에|$)'
hit '사물존칭'       '되셨|나오셨|이십니다'
echo "--- 긴 문장 (20어절 초과 또는 쉼표 3개 이상) ---"
perl -CSD -Mutf8 -ne 'if(/^\s*```/){$c=!$c;next} next if $c||/^\s*(\||#|>)/||/^[a-z_]+:\s/; chomp; s/^\s*([-*+]|\d+\.)\s+//; s/`[^`]*`/X/g; for(split /(?<=[.?!])\s+/){my $w=()=/\S+/g; my $k=()=/,/g; printf "%d\t[%d어절, 쉼표 %d] %s\n",$.,$w,$k,$_ if $w>20||$k>=3}' "$F"
}
exec 3>&1
err=$( { echo "===== 제거 대상 (0건이어야 끝) ====="; removal; echo "===== 후보 (판단해서 고침, 게이트 아님) ====="; candidates; } 2>&1 >&3 )
[ -n "$err" ] && { echo "검사 중 오류가 나서 끝내지 못했습니다 (통과 아님):" >&2; echo "$err" >&2; exit 2; }
[ "$(removal | grep -c '^[0-9]')" -eq 0 ]
